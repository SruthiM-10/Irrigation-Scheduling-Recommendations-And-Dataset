# =====================================================
# Skew Analysis of Raw Irrigation Types (Single Colab Cell)
# Generates quantitative metrics + long-tail visualizations
# =====================================================

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

# ------------------------
# Load raw (unprocessed) dataset
# ------------------------
df = pd.read_csv("/content/drive/MyDrive/1:1_Sruthi_Manoj/Dataset/final_raw_dataset_updated_doi.csv")

# ------------------------
# Auto-detect irrigation type column
# ------------------------
irrigation_cols = [
    c for c in df.columns
    if "irrig" in c.lower() or "method" in c.lower()
]

assert len(irrigation_cols) > 0, "No irrigation-related column found"
IRR_COL = irrigation_cols[0]

print(f"Using irrigation column: {IRR_COL}")

# ------------------------
# Frequency distribution
# ------------------------
freq = df[IRR_COL].value_counts()
n_types = len(freq)
n_samples = freq.sum()

print(f"\nTotal samples: {n_samples}")
print(f"Total unique irrigation types: {n_types}")

# ------------------------
# Categorical skew metrics
# ------------------------
cum_frac = freq.cumsum() / n_samples

top_5_frac = cum_frac.iloc[4]
top_10_frac = cum_frac.iloc[int(0.1 * n_types) - 1]
top_20_frac = cum_frac.iloc[int(0.2 * n_types) - 1]
bottom_50_frac = 1 - cum_frac.iloc[int(0.5 * n_types) - 1]

p = freq / n_samples
entropy = -np.sum(p * np.log(p))
max_entropy = np.log(n_types)
norm_entropy = entropy / max_entropy

print("\n=== Categorical Skew Metrics ===")
print(f"Top 5 irrigation types account for: {top_5_frac:.2%}")
print(f"Top 10% of irrigation types account for: {top_10_frac:.2%}")
print(f"Top 20% of irrigation types account for: {top_20_frac:.2%}")
print(f"Bottom 50% of irrigation types account for: {bottom_50_frac:.2%}")
print(f"Normalized entropy (0=skewed, 1=uniform): {norm_entropy:.3f}")

# ------------------------
# Plot 1: Rank–Frequency (Log–Log)
# ------------------------
plt.figure()
plt.loglog(range(1, n_types + 1), freq.values, marker="o", linestyle="none")
plt.xlabel("Irrigation Type Rank")
plt.ylabel("Frequency")
plt.title("Long-Tail Distribution of Raw Irrigation Types")
plt.show()

# ------------------------
# Plot 2: Pareto Curve
# ------------------------
plt.figure()
plt.plot(cum_frac.values)
plt.axhline(0.8, linestyle="--")
plt.xlabel("Irrigation Types (ranked by frequency)")
plt.ylabel("Cumulative Fraction of Samples")
plt.title("Pareto Curve of Irrigation Type Coverage")
plt.show()

# ------------------------
# Plot 3: Head of Distribution
# ------------------------
head_k = min(20, n_types)
plt.figure()
freq.head(head_k).plot(kind="bar")
plt.xlabel("Irrigation Type")
plt.ylabel("Count")
plt.title(f"Top {head_k} Irrigation Types (Head of Distribution)")
plt.show()

# ------------------------
# Print examples
# ------------------------
print("\nTop 10 irrigation types:")
print(freq.head(10))

print("\nBottom 10 irrigation types (rarest):")
print(freq.tail(10))


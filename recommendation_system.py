def is_valid(number_of_unique_methods, bucket_num):
  if bucket_num == 1 or bucket_num == 2:
    return number_of_unique_methods == bucket_num
  return number_of_unique_methods >= bucket_num # 3

def choose_best_method(unique_methods, predicted_yields):
  if len(unique_methods) == 2:
    diff = abs(predicted_yields[1] - predicted_yields[0])
    if diff >= PLANT_YIELD_DIFF_THRESHOLD:
      return unique_methods[predicted_yields.index(max(predicted_yields))]
    else:
      return "No substantial difference"
  else:
    ranking = sorted(zip(unique_methods, predicted_yields), key=lambda pair: pair[1], reverse=True)
    methods_ranking, sorted_yields = zip(*ranking)
    print(sorted_yields)

    for i in range(0, len(methods_ranking) - 1):
      diff = sorted_yields[i] - sorted_yields[i + 1]
      if diff < PLANT_YIELD_DIFF_THRESHOLD:
        print(f"No substantial difference between {methods_ranking[i]} and {methods_ranking[i + 1]}")

    return methods_ranking

def evaluate_system(papers, bucket_num):
  global model
  global group_cols

  true_best_methods = []
  predicted_best_methods = []

  for paper in papers:
    all_experiments = paper.get("all_experiments")
    for experiment in all_experiments:

      unique_methods = experiment.get("unique_methods")
      assert is_valid(len(unique_methods), bucket_num)

      if bucket_num == 2:
        print(f"Comparing {unique_methods[0]} with {unique_methods[1]}")

      experiment_features = experiment.get("experiment").copy()
      experiment_features['plant_yield_kg_per_hectare'] = experiment_features.groupby(group_cols)['plant_yield_kg_per_hectare'].transform('mean')
      experiment_features = experiment_features.drop_duplicates(subset=group_cols, keep='first')

      best_irrigation_scheduling_method = choose_best_method(experiment_features["irrigation_scheduling_method_standardized"].tolist(), experiment_features["plant_yield_kg_per_hectare"].tolist())
      true_best_methods.append(best_irrigation_scheduling_method)
      print("True best: ", best_irrigation_scheduling_method)

      predicted_yields = []
      for method_label in unique_methods:
        model_input = experiment_features[CAT_COLUMNS + NUMERIC_COLUMNS].iloc[0].to_frame().T.copy()
        model_input["irrigation_scheduling_method_standardized"] = method_label
        predicted_plant_yield = model.predict(model_input)[0]
        predicted_yields.append(predicted_plant_yield)

      if bucket_num == 2:
        predicted_best_method = choose_best_method(unique_methods, predicted_yields)
        predicted_best_methods.append(predicted_best_method)
        print("Predicted: ", predicted_best_method)
        print()
      else:
        predicted_best_method_ranking = choose_best_method(unique_methods, predicted_yields)
        predicted_best_methods.append(predicted_best_method_ranking)
        print("Predicted: ", predicted_best_method_ranking)
        print()

  return true_best_methods, predicted_best_methods


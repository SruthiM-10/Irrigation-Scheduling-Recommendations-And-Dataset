"""### Main Buckets Methodology"""

def classify(group, papers_bucket_1, papers_bucket_2, papers_bucket_3, papers_info, is_test= False):  # if multiple locations where they tested the irrigation scheduling methods in one paper
  print("Starting classification")
  # all metadata columns should be constant and not make an impact
  assert len(group.drop_duplicates(subset=METADATA_COLS)) == 1, f"{group.drop_duplicates(subset=METADATA_COLS)}"

  group_cols = list(set(group.columns) - set(METADATA_COLS) - {"irrigation_scheduling_method_standardized", "plant_yield_kg_per_hectare"})
  # need to make all other data constant within an experiment, so that its only irrigation scheduling method and other unknown variables (not in dataset) that influence plant yield

  experiments = group.groupby(by=group_cols) # experiments are ideally a comparison between irrigation scheduling methods to see their specific effect on plant yield
  print("Finished grouping by unique experiment inside paper")

  curr_bucket_1 = []
  curr_bucket_2 = []
  curr_bucket_3 = []

  for _, experiment in experiments:
    unique_methods = experiment["irrigation_scheduling_method_standardized"].unique()

    if len(unique_methods) == 1:
      group.loc[experiment.index, "scheduling_method_bucket"] = 1
      curr_bucket_1.append({
          "unique_methods": unique_methods,
          "experiment": experiment
      })
    elif len(unique_methods) == 2:
      group.loc[experiment.index, "scheduling_method_bucket"] = 2
      curr_bucket_2.append({
          "unique_methods": unique_methods,
          "experiment": experiment
      })
    else:
      group.loc[experiment.index, "scheduling_method_bucket"] = 3
      curr_bucket_3.append({
          "unique_methods": unique_methods,
          "experiment": experiment
      })

  if len(curr_bucket_1) > 0:
    papers_bucket_1.append({
        'paper_identifier': group["processed_at"].iloc[0],
        'all_experiments': curr_bucket_1})
  if len(curr_bucket_2) > 0:
    papers_bucket_2.append({
        'paper_identifier': group["processed_at"].iloc[0],
        'all_experiments': curr_bucket_2})
  if len(curr_bucket_3) > 0:
    papers_bucket_3.append({
        'paper_identifier': group["processed_at"].iloc[0],
        'all_experiments': curr_bucket_3})
  papers_info.append({
      'paper_identifier': group["processed_at"].iloc[0],
      'experiments_in_bucket_1': len(curr_bucket_1),
      'experiments_in_bucket_2': len(curr_bucket_2),
      'experiments_in_bucket_3': len(curr_bucket_3)
  })

  return group

def group_by_buckets(df):
  papers_bucket_1 = [] # unique experiments (different locations, crop type, etc) per paper that only test 1 method
  papers_bucket_2 = []
  papers_bucket_3 = []
  # some papers might be across multiple buckets

  papers_info = []

  df_grouped = df.groupby("processed_at").apply(lambda group: classify(group, papers_bucket_1, papers_bucket_2, papers_bucket_3, papers_info))
  df_grouped.reset_index(drop=True, inplace=True)
  print("Finished grouping and classification")

  samples_bucket_1 = df_grouped.loc[df_grouped["scheduling_method_bucket"] == 1]
  samples_bucket_2 = df_grouped.loc[df_grouped["scheduling_method_bucket"] == 2]
  samples_bucket_3 = df_grouped.loc[df_grouped["scheduling_method_bucket"] == 3]

  return (papers_bucket_1, papers_bucket_2, papers_bucket_3), (samples_bucket_1, samples_bucket_2, samples_bucket_3), papers_info


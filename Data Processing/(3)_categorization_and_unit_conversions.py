# Options: 'coarse sands', 'fine sands', 'loamy sands', 'sandy loams', 'fine sandy loams', 'silt loams',  'silty clay loams', 'silty clay', 'clay'

def categorize_soil_type(soil):
  if pd.isna(soil):
    return soil

  soil = soil.lower()
  if any(k in soil for k in ["fine sandy loam", "sandy silt"]):
    return "fine sands"

  if any(k in soil for k in ["loamy sand", "loamy-sandy", "hezel", "peat"]):
    return "loamy sands"

  if any(k in soil for k in ["sandy loam", "arenos", "oshtemo", "light grey soil"]):
    return "sandy loams"

  if any(k in soil for k in ["silty clay loam", "pullman", "arcillo limoso"]):
    return "silty clay loams"

  if any(k in soil for k in ["silty clay", "vaiden"]):
    return "silty clay"

  if any(k in soil for k in ["silt", "mineral", "loess", "alluvial", "calcareous"]):
    return "silt loams"

  if any(k in soil for k in ["sandy clay", "sandy-clay", "loam", "frank", "orthrosol", "xerorthents"]):
    return "sandy clay loams"

  if any(k in soil for k in ["clay", "red soil", "vertisol", "nitis", "vermelho", "oxisol", "latosol", "argissolo", "kandosol"]):
    return "clay"

  if any(k in soil for k in ["sand"]):
    return "coarse sands"

  print(soil, "not account for")
  return soil


class PlantYieldItem(BaseModel):
  model_config = ConfigDict(extra="forbid")
  numerator_unit: str
  denominator_unit: str
  value: float
  cleaning_notes: str

class PlantYieldLLM(BaseModel):
    """List of references extracted from a paper."""
    model_config = ConfigDict(extra="forbid")
    yield_list: List[PlantYieldItem] = Field(
        description="List of information for plant yield values"
    )

def standardize_plant_yield(df: pd.DataFrame) -> pd.DataFrame:
    """Convert plant_yield to standardized kg/hectare"""
    print("Standardizing plant_yield...")

    # Get sample values to understand the format
    sample_yields = df['plant_yield'].dropna().head(10).tolist()
    print(f"Sample yield values: {sample_yields}")

    prompt = """
You are given plant yield value(s) from agricultural data. Your task is to determine the current unit of these values.
If there are multiple numerical plant yield values (often comma-separated), return them all as separate objects.

Analyze the format of each value and provide:
  1. numerator_unit: The unit that is in the numerator. Options: kg, ton, quart, Mg, g, quintals
  2. denominator_unit: The unit that is in the denominator. Options: ha, ac, m2, hm2, da, 500 m2
  3. value: the float value for plant yield. Consider commas as thousands separators not a decimal.
  4. cleaning_notes: notes about any extra information associated with each value in the input string

If the numerator/denominator unit is not one of the above options, return "NA".
Return ONLY as a JSON array of objects.

Yield values: {values}
    """

    def convert_yield(numerator_unit, denominator_unit, value):
      if "ton" in numerator_unit:
        value *= 907.185
      elif "quart" in numerator_unit:
        value *= 0.9464
      elif "quintal" in numerator_unit:
        value *= 100
      elif "Mg" in numerator_unit:
        value *= 1000
      elif "kg" in numerator_unit:
        pass
      elif "g" in numerator_unit:
        value /= 1000

      if "ha" in denominator_unit or "hm2" in denominator_unit:
          return value
      if "ac" in denominator_unit:
        return value * 2.471
      if "500 m2" in denominator_unit:
        return value * 20
      if "m2" in denominator_unit:
        return value * 10000
      if "da" in denominator_unit:
        return value * 0.2471

      print(numerator_unit, denominator_unit, "not accounted for")
      return None

    extra_rows_to_add = []
    # Extract numerical values and convert
    def extract_and_convert_yield(row):
        value = row["plant_yield"]
        if pd.isna(value):
            print("Null plant yield")
            return row

        # Extract numbers from string
        response = call_gpt_api(llm_type= PlantYieldLLM, prompt= prompt.format(values=value)).yield_list
        if len(response) < 1:
          print("Error: ", value)
          return row
        analysis = response[0].model_dump()

        row["plant_yield_kg_per_hectare"] = convert_yield(analysis["numerator_unit"], analysis["denominator_unit"], analysis["value"])
        row['plant_yield_notes'] = analysis['cleaning_notes']

        if len(response) > 1:
          for i in range(1, len(response)):
            val = response[i]
            other_analysis = val.model_dump()
            new_row = row.copy()

            new_row["plant_yield_kg_per_hectare"] = convert_yield(other_analysis["numerator_unit"], other_analysis["denominator_unit"], other_analysis["value"])
            new_row['plant_yield_notes'] = other_analysis['cleaning_notes']
            extra_rows_to_add.append(new_row)

        return row

    df = df.apply(extract_and_convert_yield, axis= 1)

    return df, extra_rows_to_add

